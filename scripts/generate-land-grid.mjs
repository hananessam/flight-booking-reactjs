// One-off generator: samples real coastline data (world-atlas) on a lon/lat grid
// and bakes the resulting land points into a source file. Run with:
//   node scripts/generate-land-grid.mjs
// Not part of the app bundle — world-atlas/d3-geo/topojson-client are dev-only.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { feature } from 'topojson-client'
import { geoContains } from 'd3-geo'
import landTopology from 'world-atlas/land-110m.json' with { type: 'json' }

const __dirname = dirname(fileURLToPath(import.meta.url))

const LAT_TOP = 78
const LAT_BOTTOM = -60
const STEP = 2.4

const land = feature(landTopology, landTopology.objects.land)

const points = []
for (let lat = LAT_TOP; lat >= LAT_BOTTOM; lat -= STEP) {
  for (let lon = -180; lon <= 180; lon += STEP) {
    if (geoContains(land, [lon, lat])) {
      points.push([Math.round(lon * 10) / 10, Math.round(lat * 10) / 10])
    }
  }
}

const out = `// GENERATED by scripts/generate-land-grid.mjs — do not edit by hand.
// Sampled from world-atlas land-110m coastline data on a ${STEP}deg grid,
// lat ${LAT_BOTTOM} to ${LAT_TOP}. Re-run the script to regenerate.
export const LAT_TOP = ${LAT_TOP}
export const LAT_BOTTOM = ${LAT_BOTTOM}

/** [lon, lat] pairs that fall on land. */
export const LAND_GRID: [number, number][] = ${JSON.stringify(points)}
`

const outPath = join(__dirname, '..', 'src', 'components', 'flight-dashboard', 'landGrid.generated.ts')
writeFileSync(outPath, out)
console.log(`wrote ${points.length} land points to ${outPath}`)
